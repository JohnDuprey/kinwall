import { test } from 'node:test';
import assert from 'node:assert/strict';
import { join } from 'node:path';
import { createApp } from '../src/app.ts';
import { openDb, applyMigrations } from '../src/d1-sqlite.ts';
import { createApiKey } from '../src/auth.ts';

test('routine one-time requirements survive completion and replacement by name, only for that child', async () => {
  const db = openDb(':memory:'); applyMigrations(db, join(import.meta.dirname, '..', 'migrations'));
  const app = createApp(), env = { DB: db, ADMIN_API_KEY: 'parent' } as any;
  const req = (path: string, method = 'GET', body?: unknown) => app.request(path, { method, headers: { Authorization: 'Bearer parent', 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) }, env);
  const member = async (name: string) => (await req('/api/members', 'POST', { name, color: '#557799' })).json() as Promise<any>;
  const maya = await member('Maya'), leo = await member('Leo'), path = `/api/routine-mode/${maya.id}`;
  const read = async () => (await req(path)).json() as Promise<any>;
  const date = (await read()).date;
  const chore = async (title: string, extra = {}) => (await req('/api/chores', 'POST', { title, memberId: maya.id, dueDate: date, needsApproval: false, ...extra })).json() as Promise<any>;
  const original = await chore('Clean your room');
  const child = await createApiKey(db, 'Maya iPad', 'display', { owner: maya.id, deviceKind: 'kid' });
  const pending = await chore('Water plants', { needsApproval: true });
  const tick = await app.request(`/api/chores/${pending.id}/complete`, { method: 'POST', headers: { Authorization: `Bearer ${child.key}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ date }) }, env);
  assert.equal(tick.status, 200);
  assert.equal((await read()).availableChores.some((c: any) => c.id === pending.id), true, 'pending approval remains selectable');
  const repeat = await chore('Clean your room', { rrule: 'FREQ=DAILY' });
  const unfinished = await chore('Pack your bag');
  const policy = { enabled: true, cutoff: '23:59', requiredChoreIds: [original.id] };
  assert.equal((await req(path, 'PUT', policy)).status, 200);
  assert.deepEqual((await read()).requiredOneTimeChoreNames, ['Clean your room']);
  const childRead = await (await app.request(path, { headers: { Authorization: `Bearer ${child.key}` } }, env)).json() as any;
  assert.equal(childRead.requiredChoreIds, null, 'older child apps must not interpret name-only rules as schedule-only');
  assert.deepEqual(childRead.requiredOneTimeChoreNames, ['Clean your room']);
  assert.equal((await req(`/api/chores/${original.id}/complete`, 'POST', { date })).status, 200);
  assert.equal((await req(`/api/chores/${repeat.id}/complete`, 'POST', { date })).status, 200);
  const completed = await read();
  assert.equal(completed.availableChores.some((c: any) => c.id === original.id), false, 'completed one-time chores leave the settings picker');
  assert.equal(completed.availableChores.some((c: any) => c.id === repeat.id), true, 'repeating chores remain selectable');
  assert.equal(completed.availableChores.some((c: any) => c.id === unfinished.id), true);
  assert.equal(completed.remaining.length, 0);
  assert.equal((await req(`/api/chores/${original.id}/complete?date=${date}`, 'DELETE')).status, 200);
  assert.equal((await read()).availableChores.some((c: any) => c.id === original.id), true, 'undo brings a one-time chore back');
  await req(`/api/chores/${original.id}/complete`, 'POST', { date });
  assert.equal((await req(`/api/chores/${original.id}`, 'DELETE')).status, 200);
  const replacement = await chore('  CLEAN   your room  ');
  await chore('Clean your room!');
  const future = new Date(`${date}T12:00:00Z`); future.setUTCDate(future.getUTCDate() + 2);
  await chore('Clean your room', { dueDate: future.toISOString().slice(0, 10) });
  await chore('Clean your room', { memberId: leo.id });
  const later = await read();
  assert.equal(later.total, 1, 'similar names, future dates and recurring chores do not inherit the rule');
  assert.deepEqual(later.remaining.map((c: any) => c.id), [replacement.id]);
  assert.equal(later.availableChores.find((c: any) => c.id === replacement.id).oneTime, true);
  assert.equal(later.availableChores.find((c: any) => c.id === repeat.id).oneTime, false);
  assert.deepEqual((await (await req(`/api/routine-mode/${leo.id}`)).json() as any).requiredOneTimeChoreNames, []);
  assert.equal((await req(path, 'PUT', { ...policy, requiredChoreIds: [] })).status, 200);
  assert.deepEqual((await read()).requiredOneTimeChoreNames, ['Clean your room'], 'older clients cannot erase saved name rules by omitting the field');
  assert.equal((await req(path, 'PUT', { ...policy, requiredChoreIds: [], requiredOneTimeChoreNames: [] })).status, 200);
  assert.equal((await read()).total, 0, 'a parent can remove the saved name requirement');
});
